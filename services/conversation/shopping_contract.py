"""Generate the additive browser API contract without rewriting the frozen demo contract."""

import argparse
from pathlib import Path
from types import SimpleNamespace

import yaml

from services.conversation.app import create_app

PATH = Path(__file__).resolve().parents[2] / "contracts/http/shopping.yaml"


def document():
    state = SimpleNamespace(events=SimpleNamespace(mode="stub"))
    schema = create_app(state=state, mode="stub", purpose="contract_test").openapi()
    schema["info"] = {
        "title": "ShopTalk browser and contextual conversation API",
        "version": "1.0.0",
        "description": (
            "Additive shopping experience. Cart, quote and checkout use conversation.yaml."
        ),
    }
    schema["paths"] = {
        path: value
        for path, value in schema["paths"].items()
        if path.startswith("/v1/store/")
        or path
        in {
            "/v1/sessions/{session_id}",
            "/v1/sessions/{session_id}/shopping-turns",
        }
    }
    return schema


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    arguments = parser.parse_args()
    schema = document()
    if arguments.check:
        return (
            0 if PATH.exists() and yaml.safe_load(PATH.read_text(encoding="utf-8")) == schema else 1
        )
    PATH.write_text(
        "# Generated by python -m services.conversation.shopping_contract\n"
        + yaml.safe_dump(schema, sort_keys=False),
        encoding="utf-8",
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
