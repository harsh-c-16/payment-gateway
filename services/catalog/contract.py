"""Generate or check the catalogue OpenAPI and data schemas from the code that serves them."""

import argparse
import json
import sys
from pathlib import Path

import yaml

from services.catalog.app import create_app
from shared.contracts import catalog as dtos

ROOT = Path(__file__).resolve().parents[2]
PATH = ROOT / "contracts/http/catalog.yaml"
DATA = ROOT / "contracts/data/catalog"
DATA_SCHEMAS = {
    "source_manifest": dtos.SourceManifest,
    "normalized_manifest": dtos.NormalizedCatalogManifest,
    "sku_manifest": dtos.SkuManifest,
    "facet_dictionary": dtos.FacetDictionary,
    "catalog_profile": dtos.CatalogProfile,
    "catalog_load_report": dtos.CatalogLoadReport,
    "embedding_manifest": dtos.EmbeddingManifest,
}


def document():
    return create_app(db=object(), events=object()).openapi()


def data_schemas():
    return {
        DATA / f"{name}.schema.json": json.dumps(model.model_json_schema(), indent=2) + "\n"
        for name, model in DATA_SCHEMAS.items()
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    arguments = parser.parse_args()
    if arguments.check:
        stale = yaml.safe_load(PATH.read_text(encoding="utf-8")) != document() or any(
            not path.is_file() or path.read_text(encoding="utf-8") != text
            for path, text in data_schemas().items()
        )
        if stale:
            print("catalogue contracts are stale; rerun without --check")
            return 1
        return 0
    for path, text in data_schemas().items():
        path.write_text(text, encoding="utf-8")
    PATH.write_text(
        "# Generated by `python -m services.catalog.contract`. Do not edit by hand.\n"
        + yaml.safe_dump(document(), sort_keys=False),
        encoding="utf-8",
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
